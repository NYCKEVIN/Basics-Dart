/**
 * La función [main] es el punto de partida. 
 * Sin esta función, el compilador no sabría qué ejecutar.
 */
void main() {
  // 'print' es una función interna de Dart que muestra información en la consola.
  // Las cadenas de texto (Strings) pueden ir en comillas simples o dobles.
  print('¡Hola Mundo! Este es mi inicio en Dart.');
  
  // Tip de experto: En Dart 3+, puedes omitir los argumentos 
  // si no vas a procesar datos externos al ejecutar el script.
}

